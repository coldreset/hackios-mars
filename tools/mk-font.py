"""Bake an 8x16 monospace glyph set for the loader (ASCII 32..126)."""
from PIL import Image, ImageDraw, ImageFont
import os

here = os.path.dirname(os.path.abspath(__file__)) or "."
CELL_W, CELL_H = 8, 16
face = ImageFont.truetype("C:/Windows/Fonts/consola.ttf", 15)

rows = []
for code in range(32, 127):
    img = Image.new("L", (CELL_W, CELL_H), 0)
    d = ImageDraw.Draw(img)
    d.text((0, -1), chr(code), font=face, fill=255)
    bits = []
    for y in range(CELL_H):
        byte = 0
        for x in range(CELL_W):
            if img.getpixel((x, y)) > 96:
                byte |= 1 << (7 - x)
        bits.append(byte)
    rows.append(bits)

lines = ["/* generated by tools/mk-font.py: 8 x 16 cells, ASCII 32..126, one byte per row */",
         "#define FONT_FIRST 32",
         "#define FONT_LAST 126",
         "#define FONT_WIDTH 8",
         "#define FONT_HEIGHT 16",
         "static const unsigned char font_bits[%d][%d] = {" % (len(rows), CELL_H)]
for bits in rows:
    lines.append("\t{ " + ", ".join("0x%02x" % b for b in bits) + " },")
lines.append("};")

out = os.path.join(here, "font.h")
with open(out, "w", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print(out, os.path.getsize(out))

# a quick look at the sheet so it can be eyeballed
sheet = Image.new("L", (CELL_W * 95, CELL_H), 0)
for i, bits in enumerate(rows):
    for y in range(CELL_H):
        for x in range(CELL_W):
            if bits[y] & (1 << (7 - x)):
                sheet.putpixel((i * CELL_W + x, y), 255)
sheet.resize((CELL_W * 95 * 4, CELL_H * 4), Image.NEAREST).save(os.path.join(here, "font-sheet.png"))
