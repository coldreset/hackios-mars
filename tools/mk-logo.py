"""Turn the project mark into a compact paletted C header for the loader.

Index 0 is the boot screen's own background colour, so the mark can be
blitted opaquely without an alpha channel.
"""
from PIL import Image
import os

here = os.path.dirname(os.path.abspath(__file__)) or "."
SIZE = 256
COLORS = 32
BG = (0x0c, 0x0c, 0x0e)

src = Image.open(os.path.join(here, "coldreset-logo.png")).convert("RGBA")
corner = src.getpixel((4, 4))
px = src.load()
mask = Image.new("L", src.size, 255)
mp = mask.load()
for y in range(src.size[1]):
    for x in range(src.size[0]):
        r, g, b, a = px[x, y]
        if abs(r - corner[0]) < 14 and abs(g - corner[1]) < 14 and abs(b - corner[2]) < 14:
            px[x, y] = (r, g, b, 0)
            mp[x, y] = 0

flat = Image.new("RGB", src.size, BG)
flat.paste(src, (0, 0), src)
small_mask = mask.resize((SIZE, SIZE), Image.LANCZOS)
small_rgb = flat.resize((SIZE, SIZE), Image.LANCZOS)
painted = Image.new("RGB", (SIZE, SIZE), BG)
painted.paste(small_rgb, (0, 0), small_mask)
quant = painted.quantize(colors=COLORS - 1, method=Image.MEDIANCUT, dither=Image.NONE)
indices = list(quant.get_flattened_data() if hasattr(quant, "get_flattened_data") else quant.getdata())
palette = quant.getpalette()[: (COLORS - 1) * 3]

# shift every index up by one so that 0 can mean "background"
indices = [i + 1 for i in indices]
palette = list(BG) + palette

lines = ["/* generated by tools/mk-logo.py: 256 x 256, %d colours, index 0 is the screen background */" % COLORS,
         "#define LOGO_SIZE %d" % SIZE,
         "static const unsigned int logo_palette[%d] = {" % COLORS]
for i in range(COLORS):
    r, g, b = palette[i * 3], palette[i * 3 + 1], palette[i * 3 + 2]
    lines.append("\t0xff%02x%02x%02xu," % (r, g, b))
lines.append("};")
lines.append("static const unsigned char logo_index[%d] = {" % (SIZE * SIZE))
row = []
for v in indices:
    row.append("0x%02x," % v)
    if len(row) == 32:
        lines.append("\t" + "".join(row))
        row = []
if row:
    lines.append("\t" + "".join(row))
lines.append("};")

out = os.path.join(here, "logo.h")
with open(out, "w", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print(out, os.path.getsize(out))
