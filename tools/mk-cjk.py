"""Bake the handful of Chinese characters the boot screen needs into a 16 x 16
bitmap font, so the loader can print them without carrying a whole CJK font."""
from PIL import Image, ImageDraw, ImageFont
import os

here = os.path.dirname(os.path.abspath(__file__)) or "."
CELL = 16

chars = "等待主机已连接正在引导音量键选择电源确认启动诊断重到安卓"

# Microsoft YaHei renders CJK well at small sizes; fall back to SimSun.
candidates = [
    ("C:/Windows/Fonts/msyh.ttc", 15),
    ("C:/Windows/Fonts/msyhbd.ttc", 15),
    ("C:/Windows/Fonts/simsun.ttc", 16),
]
font = None
for path, size in candidates:
    try:
        font = ImageFont.truetype(path, size)
        used = os.path.basename(path) + " %d" % size
        break
    except Exception:
        continue
if font is None:
    raise SystemExit("no CJK font found")

glyphs = []
for ch in chars:
    img = Image.new("L", (CELL * 4, CELL * 4), 0)
    d = ImageDraw.Draw(img)
    d.text((CELL, CELL), ch, font=font, fill=255)
    box = img.getbbox()
    if box is None:
        glyphs.append([0] * 32)
        continue
    crop = img.crop(box)
    # centre the ink in the cell, never scaling it
    w, h = crop.size
    canvas = Image.new("L", (CELL, CELL), 0)
    canvas.paste(crop, ((CELL - w) // 2, (CELL - h) // 2))
    rows = []
    px = canvas.load()
    for y in range(CELL):
        hi = lo = 0
        for x in range(CELL):
            if px[x, y] > 110:
                if x < 8:
                    hi |= 1 << (7 - x)
                else:
                    lo |= 1 << (15 - x)
        rows.append(hi)
        rows.append(lo)
    glyphs.append(rows)

out = os.path.join(here, "cjk.h")
with open(out, "w", encoding="utf-8") as f:
    f.write("/* generated by tools/mk-cjk.py: %d characters, 16 x 16 cells, two bytes a row */\n" % len(chars))
    f.write("#define CJK_COUNT %d\n\n" % len(chars))
    f.write("static const char *const cjk_char[CJK_COUNT] = {\n")
    for i in range(0, len(chars), 8):
        f.write("\t" + " ".join('"%s",' % c for c in chars[i:i + 8]) + "\n")
    f.write("};\n\nstatic const unsigned char cjk_bits[CJK_COUNT][32] = {\n")
    for ch, rows in zip(chars, glyphs):
        f.write("\t{ /* %s */\n\t  " % ch)
        f.write(", ".join("0x%02x" % b for b in rows[:16]) + ",\n\t  ")
        f.write(", ".join("0x%02x" % b for b in rows[16:]) + " },\n")
    f.write("};\n")

print(out, len(chars), "chars from", used)
