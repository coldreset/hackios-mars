#!/usr/bin/env python3
"""Put the FocalTech touch controller's firmware where a build can find it.

The firmware is FocalTech's own and is not in this repository -- it is the vendor's, the same
way the GPU's, the audio DSP's and the modem's are not. Only the devices whose touch controller
is FocalTech need it (redwood, poco-x5-pro); mars's controller is ST's and runs the firmware
already in its flash.

Two ways to give it to a build, the first preferred:

    tools/touch-fw.py /path/to/focaltech_ts_fw.bin
        writes fw-touch/focaltech_ts_fw.bin; userland/build.sh puts it in the small image's
        fw/, and drivers/input/hakios.goodix.c reads it from there at run time

    tools/touch-fw.py --header /path/to/focaltech_ts_fw.bin
        also writes drivers/input/hakios.focaltech_fw.h, so the firmware is compiled in
        (that header is git-ignored: it is the vendor's blob either way)

Where the blob is: on the phone it is /vendor/firmware/focaltech_ts_fw.bin, or a name like it
under /vendor/firmware or /vendor/firmware_mnt/image; pull it with root. Out of a stock ROM it
is inside the vendor image. Its length is a multiple of 32 (116448 for the m20 panel), because
the download writes 32-byte packets.
"""

import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)              # the repository
SIDE = os.path.dirname(ROOT)              # the directory it sits in, beside fw-gpu/, fw-wifi/, fw-audio/ ...


def usage():
    sys.stderr.write(__doc__)
    raise SystemExit(2)


def main(argv):
    header = False
    rest = []
    for a in argv:
        if a in ("-h", "--help"):
            usage()
        elif a == "--header":
            header = True
        else:
            rest.append(a)
    if len(rest) != 1:
        usage()

    blob = open(rest[0], "rb").read()
    if len(blob) < 32 or len(blob) % 32 != 0:
        sys.stderr.write("touch-fw: %s is %u bytes, not a whole number of 32-byte packets; "
                         "is it the firmware and not something else?\n" % (rest[0], len(blob)))
        return 1
    digest = hashlib.sha256(blob).hexdigest()

    out_dir = os.path.join(SIDE, "fw-touch")
    if not os.path.isdir(out_dir):
        os.makedirs(out_dir)
    out = os.path.join(out_dir, "focaltech_ts_fw.bin")
    with open(out, "wb") as f:
        f.write(blob)
    print("touch-fw: %s -> %s (%u bytes, sha256 %s)" % (rest[0], out, len(blob), digest))

    if header:
        lines = ["/* Generated by tools/touch-fw.py from fw-touch/focaltech_ts_fw.bin. Do not edit. */",
                 "#ifndef _HAKIOS_FOCALTECH_FW_H",
                 "#define _HAKIOS_FOCALTECH_FW_H",
                 "",
                 "#define FOCALTECH_FW_LENGTH %u" % len(blob),
                 "",
                 "static const unsigned char focaltech_fw[FOCALTECH_FW_LENGTH] = {"]
        for off in range(0, len(blob), 16):
            row = blob[off:off + 16]
            lines.append("\t" + ", ".join("0x%02x" % b for b in row) + ",")
        lines += ["};", "", "#endif", ""]
        hdr = os.path.join(ROOT, "drivers/input/hakios.focaltech_fw.h")
        with open(hdr, "w") as f:
            f.write("\n".join(lines))
        print("touch-fw: %s written: the firmware is compiled in" % hdr)

    print("touch-fw: build the small image again (userland/build.sh copies fw-touch/ into fw/)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
